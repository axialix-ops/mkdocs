from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from app.api.deps import получить_текущего_пользователя, получить_дб
from app.models.user import Пользователь
from app.models.order import Ордер
from app.models.position import Позиция
from app.models.wallet import Кошелек
from app.models.market_data import РыночныеДанные
from app.schemas.order import СозданиеОрдера, Ордер as СхемаОрдера
from app.schemas.position import Позиция as СхемаПозиции

router = APIRouter()

@router.post("/orders", response_model=СхемаОрдера, summary="Создать новый ордер")
def создать_ордер(ордер: СозданиеОрдера, дб: Session = Depends(получить_дб), текущий_пользователь: Пользователь = Depends(получить_текущего_пользователя)):
    """
    Размещает новый рыночный ордер на покупку или продажу.
    """
    # Получаем последнюю цену BTC/USD
    данные_о_последней_цене = дб.query(РыночныеДанные).filter(РыночныеДанные.символ == "BTC/USD").order_by(РыночныеДанные.метка_времени.desc()).first()
    if not данные_о_последней_цене:
        raise HTTPException(status_code=400, detail="Рыночные данные недоступны")

    текущая_цена = данные_о_последней_цене.цена_закрытия

    # Получаем кошельки пользователя
    кошелек_usd = дб.query(Кошелек).filter(Кошелек.id_владельца == текущий_пользователь.id, Кошелек.валюта == "USD").first()
    кошелек_btc = дб.query(Кошелек).filter(Кошелек.id_владельца == текущий_пользователь.id, Кошелек.валюта == "BTC").first()

    if ордер.сторона == "ПОКУПКА":
        # Проверяем, достаточно ли средств на USD кошельке
        требуется_usd = ордер.количество * текущая_цена
        if кошелек_usd.баланс < требуется_usd:
            raise HTTPException(status_code=400, detail="Недостаточный баланс USD")

        кошелек_usd.баланс -= требуется_usd
        кошелек_btc.баланс += ордер.количество

        # Обновляем или создаем позицию
        позиция = дб.query(Позиция).filter(Позиция.id_владельца == текущий_пользователь.id, Позиция.символ == "BTC/USD").first()
        if позиция:
            новое_количество = позиция.количество + ордер.количество
            новая_цена_входа = ((позиция.цена_входа * позиция.количество) + (текущая_цена * ордер.количество)) / новое_количество
            позиция.количество = новое_количество
            позиция.цена_входа = новая_цена_входа
        else:
            позиция = Позиция(id_владельца=текущий_пользователь.id, символ="BTC/USD", количество=ордер.количество, цена_входа=текущая_цена)
            дб.add(позиция)

    elif ордер.сторона == "ПРОДАЖА":
        # Проверяем, достаточно ли BTC на кошельке
        if кошелек_btc.баланс < ордер.количество:
            raise HTTPException(status_code=400, detail="Недостаточный баланс BTC")

        получено_usd = ордер.количество * текущая_цена
        кошелек_btc.баланс -= ордер.количество
        кошелек_usd.баланс += получено_usd

        # Обновляем или закрываем позицию
        позиция = дб.query(Позиция).filter(Позиция.id_владельца == текущий_пользователь.id, Позиция.символ == "BTC/USD").first()
        if позиция:
            позиция.количество -= ордер.количество
            if позиция.количество <= 0:
                дб.delete(позиция)

    дб_ордер = Ордер(
        id_владельца=текущий_пользователь.id,
        символ=ордер.символ,
        сторона=ордер.сторона,
        тип_ордера=ордер.тип_ордера,
        количество=ордер.количество,
        цена=текущая_цена,
        статус="ИСПОЛНЕН"
    )
    дб.add(дб_ордер)
    дб.commit()
    дб.refresh(дб_ордер)
    return дб_ордер

@router.get("/positions", response_model=list[СхемаПозиции], summary="Получить открытые позиции")
def прочитать_позиции(дб: Session = Depends(получить_дб), текущий_пользователь: Пользователь = Depends(получить_текущего_пользователя)):
    """
    Возвращает список всех открытых позиций пользователя с рассчитанным P&L.
    """
    позиции = дб.query(Позиция).filter(Позиция.id_владельца == текущий_пользователь.id).all()
    # Обновляем P&L для каждой позиции
    данные_о_последней_цене = дб.query(РыночныеДанные).filter(РыночныеДанные.символ == "BTC/USD").order_by(РыночныеДанные.метка_времени.desc()).first()
    if данные_о_последней_цене:
        текущая_цена = данные_о_последней_цене.цена_закрытия
        for позиция in позиции:
            позиция.pnl = (текущая_цена - позиция.цена_входа) * позиция.количество
    return позиции
