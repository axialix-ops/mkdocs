import asyncio
import random
import datetime
from sqlalchemy.orm import Session
from app.db.session import SessionLocal
from app.models.market_data import РыночныеДанные

async def генерировать_рыночные_данные():
    """
    Асинхронная задача для генерации и сохранения симулированных рыночных данных (свечей).
    """
    дб: Session = SessionLocal()

    # Получаем последнюю свечу из базы данных
    последняя_свеча = дб.query(РыночныеДанные).order_by(РыночныеДанные.метка_времени.desc()).first()

    if последняя_свеча:
        цена_открытия = последняя_свеча.цена_закрытия
        последняя_метка_времени = последняя_свеча.метка_времени
    else:
        # Начальные данные, если база пуста
        цена_открытия = 60000.0
        последняя_метка_времени = datetime.datetime.utcnow() - datetime.timedelta(minutes=1)

    while True:
        # Генерируем случайное изменение цены
        процент_изменения = random.uniform(-0.001, 0.001)
        цена_закрытия = цена_открытия * (1 + процент_изменения)

        # Генерируем максимум и минимум
        максимум = max(цена_открытия, цена_закрытия) * random.uniform(1, 1.0005)
        минимум = min(цена_открытия, цена_закрытия) * random.uniform(0.9995, 1)

        # Генерируем объем
        объем = random.uniform(1, 10)

        # Создаем новую свечу
        новая_свеча = РыночныеДанные(
            символ="BTC/USD",
            метка_времени=последняя_метка_времени + datetime.timedelta(minutes=1),
            цена_открытия=цена_открытия,
            максимум=максимум,
            минимум=минимум,
            цена_закрытия=цена_закрытия,
            объем=объем
        )

        дб.add(новая_свеча)
        дб.commit()

        # Обновляем цену открытия для следующей свечи
        цена_открытия = цена_закрытия
        последняя_метка_времени = новая_свеча.метка_времени

        print(f"Сгенерирована новая свеча: {новая_свеча.метка_времени} - Закрытие: {новая_свеча.цена_закрытия}")

        # В реальном приложении здесь лучше использовать управляемую задержку,
        # но для симуляции подойдет и простой sleep.
        await asyncio.sleep(60) # Генерируем новую свечу каждую минуту
